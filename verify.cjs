const fs=require('fs');
const vm=require('vm');
const assert=require('assert');
const storage=new Map();
let rejectArchive=false;
const context={localStorage:{getItem:key=>storage.get(key)||null,setItem:(key,value)=>{if(rejectArchive&&key==='one-hour-plan-archive-v1')throw new Error('quota');storage.set(key,value);}},document:{addEventListener:()=>{},querySelectorAll:()=>[],querySelector:()=>({textContent:'',style:{}})}};
vm.createContext(context);
for(const file of ['plan.js','dataset.js','legacy-data.js','supplemental.js','library.js','illustrations.js','supplemental-art.js','program-ui.js'])vm.runInContext(fs.readFileSync(file,'utf8'),context);
vm.runInContext(fs.readFileSync('app.js','utf8').split("$('#days').addEventListener")[0],context);
const run=code=>vm.runInContext(code,context);
run('renderWeek=()=>{};renderWorkout=()=>{};toast=()=>{};');
assert.equal(run('DATASET_LIBRARY.length'),1324);
assert.equal(run('SUPPLEMENTAL_EXERCISES.length'),8);
assert.equal(run('new Set(EXERCISE_LIBRARY.map(e=>e.id)).size'),1332);
assert(run('TRAINING_PLAN.every(plan=>originalExerciseIds(plan).every(id=>EXERCISE_BY_ID[id]))'));
assert(run(`filterExercises({target:'pectorals',query:'中立握'}).some(e=>e.id==='supp-floor-press')`));
assert(run('TRAINING_PLAN.every(plan=>plan.exercises.every(tuple=>(tuple[4].alternatives||[]).every(id=>EXERCISE_BY_ID[id])))'));
assert.deepEqual(Array.from(run('TRAINING_PLAN.slice(0,5).map(plan=>plan.exercises.reduce((sum,row)=>sum+row[1],0))')),[13,12,14,14,11]);
assert(run('TRAINING_PLAN[2].kind==="control"&&TRAINING_PLAN[2].exercises[0][4].unit==="分钟"&&TRAINING_PLAN[2].exercises[7][4].unit==="秒"'));
assert(run('EXERCISE_LIBRARY.every(exercise=>exercise.cues.length>0&&exercise.source.startsWith("https://"))'));
assert(run('EXERCISE_LIBRARY.every(e=>!/(NaN|undefined)/.test(ExerciseArt.guide(e)))'));
assert(run('LEGACY_EXERCISES.every(e=>!/(NaN|undefined)/.test(LegacyExerciseArt.guide(e)))'));
assert(run(`(()=>{const ids=[];for(let page=1;page<=28;page++)ids.push(...exercisePage(DATASET_LIBRARY,page).items.map(e=>e.datasetId));return ids.length===1324&&new Set(ids).size===1324;})()`));
assert(run('DATASET_LIBRARY.every(e=>e.instruction_steps.zh.length===e.instruction_steps.en.length)'));
// A v1 session still resolves the old Monday movements and exact original set counts.
run(`selectedDate=dateFromKey('2026-10-19');journal={'2026-10-19':{note:'legacy',exercises:PREVIOUS_TRAINING_PLAN[0].exercises.map(([,count])=>emptySets(count))}};journal['2026-10-19'].exercises[0][0]={weight:'20',reps:'12',done:true};`);
assert(run(`isValidJournal(journal)&&getPlan().version===PREVIOUS_PLAN_VERSION&&getSession().exerciseIds[0]==='neutral-pulldown'&&getSession().exercises[3].length===3`));
// Archive failure must leave the saved session and plan untouched.
rejectArchive=true;
run('startNewPlanForDate()');
assert(run(`getPlan().version===PREVIOUS_PLAN_VERSION&&getSession().exercises[0][0].weight==='20'`));
rejectArchive=false;
run('startNewPlanForDate()');
assert(run(`getPlan().version===PLAN_VERSION&&getSession().exerciseIds[0]==='ex-0327'&&getSession().exercises[0][0].weight===''&&Object.values(archivedSessions)[0].session.exercises[0][0].weight==='20'&&isValidArchive(archivedSessions)&&isValidJournal(journal)`));
// New exercises do not inherit old sets or RIR; switching back restores both.
run(`{const session=getSession();session.exercises[0][0]={weight:'8',reps:'12',done:true};session.efforts[0]='3';persistSession(session);replaceExercise(0,'ex-0292',false);}`);
assert(run(`getSession().exercises[0][0].weight===''&&getSession().efforts[0]===''`));
run(`replaceExercise(0,'ex-0327',false)`);
assert(run(`getSession().exercises[0][0].weight==='8'&&getSession().efforts[0]==='3'&&getSession().exercises[0][0].done`));
run(`replaceExercise(0,'ex-0292',true);selectedDate=dateFromKey('2026-10-26');`);
assert(run(`getSession().exerciseIds[0]==='ex-0292'&&getSession().exercises[0][0].weight===''&&isValidPlanChoices(planChoices)`));
// Old dataset v2 records, including Friday's six slots, are not rejected by the new five-slot plan.
run(`journal['2026-10-23']={note:'v2',exerciseIds:originalExerciseIds(PREVIOUS_TRAINING_PLAN[4]),exercises:PREVIOUS_TRAINING_PLAN[4].exercises.map(([,count])=>emptySets(count))};`);
assert(run(`isValidJournal(journal)&&getPlan(dateFromKey('2026-10-23')).exercises.length===6`));
assert(!run(`isValidJournal({'2026-02-30':getSession()})`));
assert(!run(`isValidExerciseIds(['not-real'],1)`));
assert(!run(`isValidPlanChoices({5:[]})`));
assert(!run(`isValidJournal({'2026-10-26':{...getSession(),planVersion:'unknown'}})`));
assert(!run(`isValidJournal({'2026-10-26':{...getSession(),efforts:['99']}})`));
assert(!run(`isValidArchive({'bad':{date:'2026-10-19',session:getSession()}})`));
run(`programStart='2026-10-19';`);
assert.equal(run(`programWeek(dateFromKey('2026-10-19'))`),1);
assert.equal(run(`programWeek(dateFromKey('2026-11-02'))`),3);
assert.equal(run(`programWeek(dateFromKey('2026-12-14'))`),9);
assert(run(`isValidBackup(JSON.parse(JSON.stringify({version:3,journal,planChoices,archivedSessions,programStart})))`));
assert(run(`isValidBackup({version:1,journal:{'2026-10-23':journal['2026-10-23']}})`));
assert(run(`isValidBackup({version:2,journal:{'2026-10-23':journal['2026-10-23']},planChoices:{4:originalExerciseIds(PREVIOUS_TRAINING_PLAN[4])}})`));
assert(!run(`isValidBackup({version:3,journal,planChoices,archivedSessions:{bad:{}},programStart})`));
console.log('PASS: 1,324 original + 8 supplemental movements, exact plan sets/alternatives/units, all diagrams, v1/v2 compatibility, archive failure protection, new-plan switching, RIR restore, recurring choices, backup validation and 8-week stages.');
